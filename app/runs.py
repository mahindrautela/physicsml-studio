"""Run records: start, list, read, stop and delete runs.

A run evaluates every selected model on every selected dataset. Its record
(run.json) is what the web page polls for progress and results. The work itself
is done by runner.py on a single background thread, so runs wait in line
instead of competing for the GPU.

Files of one run, in workspace/runs/<run_id>/:
    run.json                       record: status, settings, progress, metrics, log
    data/<dataset>/truth.npy       true fields of the trajectories kept for viewing
    pairs/<model>__<dataset>/      that model's predictions on that dataset
        onestep.npy  rollout.npy
"""
from __future__ import annotations

import json
import shutil
import threading
import uuid
from concurrent.futures import ThreadPoolExecutor
from datetime import datetime, timezone
from pathlib import Path
from typing import Callable, Optional

from pydantic import BaseModel, Field

from . import catalog
from .adapters import REGISTRY
from .config import RUNS_DIR

ACTIVE = ("queued", "running")


class RunSettings(BaseModel):
    """The options in the page's Settings panel."""

    max_trajectories: int = Field(8, ge=1, le=10000, description="Trajectories evaluated per dataset")
    rollout_steps: int = Field(0, ge=0, le=10000, description="0 = as many as the data allows")
    rollout_start: int = Field(0, ge=0, description="Time index of the last true frame given to the models")
    viz_samples: int = Field(3, ge=1, le=16, description="Trajectories saved for the viewer")
    device: str = "auto"


# ---------------------------------------------------------------- paths
def run_dir(run_id: str) -> Path:
    if not run_id.replace("-", "").isalnum():  # ids are generated by us; refuse anything path-like
        raise KeyError(run_id)
    return RUNS_DIR / run_id


def truth_file(run_id: str, dataset: str) -> Path:
    return run_dir(run_id) / "data" / dataset / "truth.npy"


def prediction_file(run_id: str, model: str, dataset: str, mode: str) -> Path:
    """mode is 'onestep' or 'rollout'."""
    return run_dir(run_id) / "pairs" / f"{model}__{dataset}" / f"{mode}.npy"


def now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


# ---------------------------------------------------------------- the store
class RunStore:
    """Keeps run records on disk, and in memory while they are running.

    ``execute(run, store, stop_event)`` does the actual work (see runner.py).
    """

    def __init__(self, execute: Callable[[dict, "RunStore", threading.Event], None]):
        self.lock = threading.RLock()  # guards every change to a running record
        self._execute = execute
        self._running: dict[str, dict] = {}
        self._stop_events: dict[str, threading.Event] = {}
        self._worker = ThreadPoolExecutor(max_workers=1, thread_name_prefix="run")
        self._mark_interrupted_runs()

    # ---- reading
    def get(self, run_id: str) -> dict:
        with self.lock:
            if run_id in self._running:  # return a copy so the caller never sees a half-written update
                return json.loads(json.dumps(self._running[run_id], default=str))
        file = run_dir(run_id) / "run.json"
        if not file.exists():
            raise KeyError(run_id)
        return json.loads(file.read_text())

    def list(self) -> list[dict]:
        """Short summaries of all runs, newest first."""
        summaries = []
        for file in RUNS_DIR.glob("*/run.json"):
            try:
                run = self.get(file.parent.name)
            except (KeyError, ValueError):
                continue
            summaries.append({
                "id": run["id"], "name": run["name"], "created": run["created"], "status": run["status"],
                "models": run["models"], "datasets": run["datasets"],
                "done": sum(p["status"] == "done" for p in run["pairs"]), "total": len(run["pairs"]),
            })
        return sorted(summaries, key=lambda r: r["created"], reverse=True)

    # ---- changing
    def start(self, model_ids: list[str], dataset_ids: list[str], settings: RunSettings,
              name: Optional[str] = None) -> dict:
        run = _new_record(model_ids, dataset_ids, settings, name)
        stop = threading.Event()
        with self.lock:
            self._running[run["id"]] = run
            self._stop_events[run["id"]] = stop
            self.save(run)
        self._worker.submit(self._execute_and_release, run, stop)
        return self.get(run["id"])

    def stop(self, run_id: str) -> None:
        with self.lock:
            if run_id not in self._stop_events:
                raise KeyError(run_id)
            self._stop_events[run_id].set()

    def delete(self, run_id: str) -> None:
        with self.lock:
            if run_id in self._running:
                raise RuntimeError("Stop the run before deleting it")
        if not run_dir(run_id).exists():
            raise KeyError(run_id)
        shutil.rmtree(run_dir(run_id))

    # ---- used by the runner
    def save(self, run: dict) -> None:
        with self.lock:
            folder = run_dir(run["id"])
            folder.mkdir(parents=True, exist_ok=True)
            tmp = folder / "run.json.tmp"
            tmp.write_text(json.dumps(run, indent=1, default=str))
            tmp.replace(folder / "run.json")  # atomic: the page never reads a half-written file

    # ---- internals
    def _execute_and_release(self, run: dict, stop: threading.Event) -> None:
        try:
            self._execute(run, self, stop)
        finally:
            with self.lock:
                self.save(run)
                self._running.pop(run["id"], None)
                self._stop_events.pop(run["id"], None)

    def _mark_interrupted_runs(self) -> None:
        """Runs that were going when the server stopped can't continue; say so."""
        for file in RUNS_DIR.glob("*/run.json"):
            try:
                run = json.loads(file.read_text())
            except ValueError:
                continue
            if run.get("status") in ACTIVE:
                run["status"] = "interrupted"
                for pair in run["pairs"]:
                    if pair["status"] in ACTIVE:
                        pair["status"] = "interrupted"
                self.save(run)


def _new_record(model_ids: list[str], dataset_ids: list[str], settings: RunSettings,
                name: Optional[str]) -> dict:
    if not model_ids or not dataset_ids:
        raise ValueError("Pick at least one model and one dataset")
    models = [catalog.get("models", m) for m in model_ids]
    datasets = [catalog.get("datasets", d) for d in dataset_ids]
    for m in models:
        if m.adapter not in REGISTRY:
            raise ValueError(f"Model '{m.name}' uses model type '{m.adapter}', which isn't installed")
    # Every model in a run is scored on the same time steps, so the model that
    # needs the most input frames decides where scoring starts.
    max_ar_order = max(int(m.config.get("ar_order", REGISTRY[m.adapter].ar_order)) for m in models)
    plural = lambda n, word: f"{n} {word}{'s' if n > 1 else ''}"  # noqa: E731
    return {
        "id": datetime.now().strftime("%Y%m%d-%H%M%S-") + uuid.uuid4().hex[:4],
        "name": name or f"{plural(len(models), 'model')} × {plural(len(datasets), 'dataset')}",
        "created": now(), "started": None, "finished": None, "status": "queued", "device": None,
        "settings": settings.model_dump(),
        "models": model_ids,
        "datasets": dataset_ids,
        "model_cards": {m.id: m.model_dump() for m in models},      # snapshot: later card edits don't change old runs
        "dataset_cards": {d.id: d.model_dump() for d in datasets},
        "max_ar_order": max_ar_order,
        "dataset_info": {},
        "pairs": [{"model": m.id, "dataset": d.id, "status": "queued", "stage": "Waiting", "progress": 0.0,
                   "error": None, "metrics": None, "timing": None, "info": None}
                  for m in models for d in datasets],
        "log": [],
    }
